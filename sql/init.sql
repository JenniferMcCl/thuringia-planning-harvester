CREATE EXTENSION IF NOT EXISTS postgis;

CREATE SCHEMA IF NOT EXISTS iris_staging;

CREATE TABLE IF NOT EXISTS iris_staging.signal_ingest (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    source_system TEXT NOT NULL,
    source_id TEXT,
    source_key TEXT NOT NULL,
    source_url TEXT,
    title TEXT,
    description TEXT,
    publication_date DATE,
    publication_date_raw TEXT,
    municipality TEXT,
    location_text TEXT,
    procedure_status TEXT,
    approval_status TEXT NOT NULL,
    industrial_status TEXT NOT NULL,
    signal_type TEXT,
    geom geometry(POINT,25832),
    distance_to_a4_m DOUBLE PRECISION,
    corridor_status TEXT NOT NULL,
    state_status TEXT DEFAULT 'unknown' NOT NULL,
    screening_status TEXT NOT NULL,
    quality_flags JSONB DEFAULT '[]'::jsonb NOT NULL,
    raw_record JSONB,
    ingest_metadata JSONB DEFAULT '{}'::jsonb NOT NULL,
    first_seen_at TIMESTAMP WITH TIME ZONE NOT NULL,
    last_seen_at TIMESTAMP WITH TIME ZONE NOT NULL,
    content_updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uq_signal_source UNIQUE (source_system, source_key),
    CONSTRAINT ck_source_key CHECK (length(source_key) > 0),
    CONSTRAINT ck_approval_status CHECK (approval_status IN ('approved', 'not_approved', 'unknown')),
    CONSTRAINT ck_industrial_status CHECK (industrial_status IN ('industrial', 'non_industrial', 'unknown')),
    CONSTRAINT ck_corridor_status CHECK (corridor_status IN ('inside', 'outside', 'unknown')),
    CONSTRAINT ck_state_status CHECK (state_status IN ('inside', 'outside', 'unknown')),
    CONSTRAINT ck_state_geometry CHECK (state_status = 'unknown' OR geom IS NOT NULL),
    CONSTRAINT ck_screening_status CHECK (screening_status IN ('accepted', 'needs_review')),
    CONSTRAINT ck_distance CHECK (distance_to_a4_m IS NULL OR (distance_to_a4_m >= 0 AND distance_to_a4_m < 'Infinity'::float8)),
    CONSTRAINT ck_corridor_geometry CHECK ((corridor_status = 'unknown' AND distance_to_a4_m IS NULL) OR (corridor_status != 'unknown' AND distance_to_a4_m IS NOT NULL AND geom IS NOT NULL)),
    CONSTRAINT ck_accepted CHECK (screening_status != 'accepted' OR (approval_status = 'approved' AND industrial_status = 'industrial' AND corridor_status = 'inside' AND state_status = 'inside' AND geom IS NOT NULL)),
    CONSTRAINT ck_flags CHECK (jsonb_typeof(quality_flags) = 'array'),
    CONSTRAINT ck_ingest_metadata CHECK (jsonb_typeof(ingest_metadata) = 'object'),
    CONSTRAINT ck_chronology CHECK (first_seen_at <= last_seen_at AND first_seen_at <= content_updated_at)
);

CREATE INDEX IF NOT EXISTS idx_signal_ingest_geom ON iris_staging.signal_ingest USING gist (geom);
